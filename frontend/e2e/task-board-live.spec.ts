import {test, expect} from "@playwright/test";
import {mkdirSync} from "node:fs";
const project = process.env.QUALITY_PROJECT || "real-srs-sds-20260929";
const images = "../artifacts/task-management";
test.beforeAll(() => mkdirSync(images, {recursive: true}));
test("真实队列看板：入口、筛选、任务详情、执行记录与自适应布局", async ({page}) => {
  const errors: string[] = [], writes: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => {if (r.url().includes("/api/") && r.method() !== "GET") writes.push(r.url());});
  await page.setViewportSize({width: 1672, height: 1000});
  await page.goto("/#/tasks");
  await expect(page.getByRole("heading", {name: "任务队列管理"})).toBeVisible();
  await expect(page.locator(".queue-name").first()).toBeVisible();
  await expect(page.locator(".queue-resources")).toContainText("qwen35-9b");
  await expect(page.locator(".queue-detail .ant-table-row").first()).toBeVisible();
  await expect(page.locator(".ant-spin-blur")).toHaveCount(0);
  await page.screenshot({path: `${images}/任务队列-桌面.png`, fullPage: true});
  await page.getByRole("tab", {name: "执行记录", exact: true}).click();
  await expect(page.locator(".queue-log")).toContainText("队列");
  await page.getByRole("tab", {name: "依赖与恢复", exact: true}).click();
  await expect(page.locator(".queue-detail-note:visible")).toContainText("中断后先等待执行器确认");
  await page.getByRole("combobox", {name: "任务类型", exact: true}).click();
  await page.locator(".ant-select-dropdown:visible").getByText("追溯任务", {exact: true}).click();
  await expect(page.locator(".queue-name")).toHaveCount(1);
  await page.getByRole("button", {name: "新建任务", exact: true}).click();
  await expect(page.getByRole("dialog")).toContainText("所属项目");
  await page.getByRole("dialog").getByRole("button", {name: /^取\s*消$/}).click();
  await page.goto(`/#/projects/${project}/tasks`);
  await expect(page.locator(".queue-breadcrumb")).toContainText("Real SRS SDS validation");
  await page.setViewportSize({width: 1024, height: 1000});
  await expect(page.locator(".queue-detail .ant-table-row").first()).toBeVisible();
  await expect(page.locator(".ant-spin-blur")).toHaveCount(0);
  await expect(page.locator(".queue-resources")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({path: `${images}/任务队列-窄屏.png`, fullPage: true});
  expect(errors).toEqual([]);expect(writes).toEqual([]);
});
